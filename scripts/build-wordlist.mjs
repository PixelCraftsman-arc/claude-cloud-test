// Builds data/words.js from two sources:
//   1. A SCOWL word list (decides which words are valid), e.g. the Debian
//      `wamerican` package's /usr/share/dict/american-english.
//   2. A "word count" frequency list (decides how common each word is), e.g.
//      hermitdave/FrequencyWords content/2018/en/en_50k.txt.
//
// Usage: node scripts/build-wordlist.mjs <scowl-list> <frequency-list>
//
// Output is a classic script that sets `globalThis.TYPOFIX_WORDS` to a
// newline-separated string of lowercase words, most frequent first, so the
// app works when index.html is opened straight from disk.

import { readFileSync, writeFileSync } from "node:fs";

const [scowlPath, freqPath] = process.argv.slice(2);
if (!scowlPath || !freqPath) {
  console.error("usage: node scripts/build-wordlist.mjs <scowl-list> <frequency-list>");
  process.exit(1);
}

const valid = new Set();
for (const raw of readFileSync(scowlPath, "utf8").split("\n")) {
  const word = raw.trim();
  // Skip possessives (the checker strips 's itself) and anything non-alphabetic.
  if (!/^[A-Za-z]+('[a-z]+)?$/.test(word) || /'s$/.test(word)) continue;
  valid.add(word.toLowerCase());
}

const ranked = [];
const seen = new Set();
for (const line of readFileSync(freqPath, "utf8").split("\n")) {
  const word = line.split(" ")[0];
  if (word && valid.has(word) && !seen.has(word)) {
    ranked.push(word);
    seen.add(word);
  }
}
const rankedCount = ranked.length;

// Valid words missing from the frequency list are still accepted, just rare.
for (const word of [...valid].sort()) {
  if (!seen.has(word)) ranked.push(word);
}

const out =
  "// Generated by scripts/build-wordlist.mjs — do not edit by hand.\n" +
  "// Word validity: SCOWL (c) Kevin Atkinson. Ranking: FrequencyWords (c) Hermit Dave.\n" +
  "// See data/README.md for licenses.\n" +
  `globalThis.TYPOFIX_RANKED_COUNT = ${rankedCount};\n` +
  `globalThis.TYPOFIX_WORDS = ${JSON.stringify(ranked.join("\n"))};\n`;

writeFileSync(new URL("../data/words.js", import.meta.url), out);
console.log(`wrote ${ranked.length} words (${rankedCount} frequency-ranked)`);
